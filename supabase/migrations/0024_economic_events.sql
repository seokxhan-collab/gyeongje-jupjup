create table if not exists economic_events (
  id uuid primary key default gen_random_uuid(),
  event_date date not null,
  title text not null,
  category text not null check (category in ('central_bank', 'employment', 'inflation', 'growth')),
  country text not null check (country in ('domestic', 'international')),
  importance text not null check (importance in ('high', 'medium')) default 'medium',
  time_label text,
  description text,
  created_at timestamptz not null default now(),
  unique (event_date, title)
);

create index if not exists economic_events_event_date_idx on economic_events (event_date);

alter table economic_events enable row level security;

drop policy if exists "public read economic_events" on economic_events;
create policy "public read economic_events" on economic_events
  for select
  to anon, authenticated
  using (true);

